# 2. 核心推理机
def inference_engine(taste, max_price):
    print(f"\n[AI推理解析] 正在检索口味: {taste} | 预算: {max_price}元")
    time.sleep(1) # 假装思考1秒，高级感拉满
    results = []
    
    # 规则推理逻辑
    for dish, info in knowledge_graph["菜品库"].items():
        # 规则：口味符合 且 价格在预算内
        if info["口味"] == taste and info["价格"] <= max_price:
            results.append(f"{dish}({info['价格']}元)")
            
    print("-" * 35)
    if results:
        print(f"✅ 推理结果：为你推荐 {', '.join(results)}")
    else:
        print("❌ 推理结果：知识库中暂无符合要求的菜品，请重新输入。")
    print("-" * 35)

